/**
 * Stay inventory from the catalogue (docs/stay-booking.md): one `stay_inventory` row per listing and
 * room type, units = beds left, rent per month, AC and attached bathroom.
 *
 * Writes scripts/sync-stay-inventory.sql, an idempotent upsert that also switches off rows no
 * longer in the catalogue (they are never deleted: bookings refer to them). Apply it with
 *   pnpm exec tsx scripts/sync-stay-inventory.ts            # regenerate the SQL file
 *   pnpm exec supabase db query -f scripts/sync-stay-inventory.sql            # local database
 *   pnpm exec supabase db query --remote -f scripts/sync-stay-inventory.sql   # production
 * src/features/stays/inventory-sync.test.ts fails when the SQL file drifts from the catalogue.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { allCatalogListings, type CatalogListing } from "@/features/catalog/listings";

export type StayInventoryRow = {
  listing_ref: string;
  room_type: "single" | "double" | "triple";
  units: number;
  rent_per_month: number;
  ac: boolean;
  attached_bathroom: boolean;
};

export function stayInventoryRows(listings: CatalogListing[] = allCatalogListings()): StayInventoryRow[] {
  return listings
    .flatMap((listing) =>
      listing.sharing.map((option) => ({
        listing_ref: listing.slug,
        room_type: option.type,
        units: option.beds_left,
        rent_per_month: option.rent,
        ac: option.ac,
        attached_bathroom: option.attached_bathroom,
      })),
    )
    .sort((a, b) => a.listing_ref.localeCompare(b.listing_ref) || a.room_type.localeCompare(b.room_type));
}

const quote = (value: string) => `'${value.replaceAll("'", "''")}'`;

export function stayInventorySql(rows: StayInventoryRow[] = stayInventoryRows()): string {
  const values = rows
    .map(
      (row) =>
        `  (${quote(row.listing_ref)}, ${quote(row.room_type)}, ${row.units}, ${row.rent_per_month}, ${row.ac}, ${row.attached_bathroom})`,
    )
    .join(",\n");
  // One statement (so `supabase db query -f` accepts it, and it is atomic on its own).
  return `-- GENERATED by scripts/sync-stay-inventory.ts from the catalogue. Do not edit by hand.
-- ${rows.length} rows. Idempotent: re-running changes nothing unless the catalogue changed.
with src (listing_ref, room_type, units, rent_per_month, ac, attached_bathroom) as (values
${values}
), upserted as (
  insert into public.stay_inventory as i (listing_ref, room_type, units, rent_per_month, ac, attached_bathroom, active)
  select listing_ref, room_type, units, rent_per_month, ac, attached_bathroom, true from src
  on conflict (listing_ref, room_type) do update
    set units = excluded.units, rent_per_month = excluded.rent_per_month, ac = excluded.ac,
        attached_bathroom = excluded.attached_bathroom, active = true
    where (i.units, i.rent_per_month, i.ac, i.attached_bathroom, i.active)
          is distinct from (excluded.units, excluded.rent_per_month, excluded.ac, excluded.attached_bathroom, true)
  returning 1
), deactivated as (
  update public.stay_inventory i set active = false
   where i.active
     and not exists (select 1 from src s where s.listing_ref = i.listing_ref and s.room_type = i.room_type)
  returning 1
)
select (select count(*) from upserted) as changed, (select count(*) from deactivated) as deactivated;
`;
}

/** Run from the repository root (pnpm runs scripts there). */
export const STAY_INVENTORY_SQL_PATH = resolve(process.cwd(), "scripts/sync-stay-inventory.sql");

if (process.argv[1]?.endsWith("sync-stay-inventory.ts")) {
  const rows = stayInventoryRows();
  writeFileSync(STAY_INVENTORY_SQL_PATH, stayInventorySql(rows));
  console.log(`Wrote ${rows.length} rows to ${STAY_INVENTORY_SQL_PATH}`);
}
